'use strict';

const STATES = Object.freeze(['NEW','INGESTING','READY_FOR_PLAN','PLAN_READY','REVIEW_REQUIRED','READY_FOR_PORTAL','PORTAL_EXECUTING','PORTAL_EXECUTED','VERIFICATION_REQUIRED','DISCHARGE_REQUIRED','FINAL_BILL_REQUIRED','FINAL_BILL_LOADED','FINAL_BILL_REVIEW_REQUIRED','MATCH_REQUIRED','READY_TO_SAVE','COMPLETED','FAILED','BLOCKED','RECOVERY_REQUIRED']);
const TRANSITIONS = Object.freeze({
  NEW: ['INGESTING'], INGESTING: ['READY_FOR_PLAN','FAILED'], READY_FOR_PLAN: ['PLAN_READY','REVIEW_REQUIRED','FAILED'],
  PLAN_READY: ['READY_FOR_PORTAL','REVIEW_REQUIRED'], REVIEW_REQUIRED: ['READY_FOR_PLAN','PLAN_READY','READY_FOR_PORTAL','FINAL_BILL_REVIEW_REQUIRED','BLOCKED'],
  READY_FOR_PORTAL: ['PORTAL_EXECUTING','REVIEW_REQUIRED'], PORTAL_EXECUTING: ['PORTAL_EXECUTED','REVIEW_REQUIRED','FAILED','RECOVERY_REQUIRED'],
  PORTAL_EXECUTED: ['VERIFICATION_REQUIRED'], VERIFICATION_REQUIRED: ['DISCHARGE_REQUIRED'], DISCHARGE_REQUIRED: ['FINAL_BILL_REQUIRED'],
  FINAL_BILL_REQUIRED: ['FINAL_BILL_LOADED','MATCH_REQUIRED','FAILED'], MATCH_REQUIRED: ['FINAL_BILL_LOADED','FINAL_BILL_REQUIRED'],
  FINAL_BILL_LOADED: ['READY_TO_SAVE','FINAL_BILL_REVIEW_REQUIRED','MATCH_REQUIRED'], FINAL_BILL_REVIEW_REQUIRED: ['READY_TO_SAVE','BLOCKED'],
  READY_TO_SAVE: ['COMPLETED','FAILED'], RECOVERY_REQUIRED: ['READY_FOR_PORTAL','REVIEW_REQUIRED','FAILED'],
  FAILED: ['RECOVERY_REQUIRED','INGESTING'], BLOCKED: ['REVIEW_REQUIRED'], COMPLETED: []
});
function assertTransition(from, to) {
  if (!STATES.includes(from) || !STATES.includes(to)) throw new Error(`Unknown case state: ${from} -> ${to}`);
  if (!TRANSITIONS[from].includes(to)) throw new Error(`Invalid case transition: ${from} -> ${to}`);
}
module.exports = { STATES, TRANSITIONS, assertTransition };
